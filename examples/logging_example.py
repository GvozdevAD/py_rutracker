"""
Примеры настройки и использования логирования в py_rutracker.

По умолчанию библиотека логирует только WARNING и выше, чтобы не засорять вывод.
Для отладки можно включить более подробное логирование.
"""
import logging
from py_rutracker import RuTrackerClient, configure_logger

# ============================================================================
# Вариант 1: Использование функции configure_logger (рекомендуется)
# ============================================================================

# Установить уровень INFO для просмотра информационных сообщений
configure_logger(level='INFO')

# Или использовать константы из модуля logging
configure_logger(level=logging.DEBUG)

# С записью в файл
configure_logger(
    level='DEBUG',
    log_to_file=True,
    log_file_path="rutracker.log"
)

# ============================================================================
# Вариант 2: Использование переменной окружения (удобно для продакшена)
# ============================================================================
# Установите переменную окружения перед запуском:
# export PY_RUTRACKER_LOG_LEVEL=DEBUG
# или
# export PY_RUTRACKER_LOG_LEVEL=INFO

# ============================================================================
# Вариант 3: Использование стандартного модуля logging
# ============================================================================
# import logging
# logging.basicConfig(
#     level=logging.INFO,
#     format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
# )

# ============================================================================
# Пример использования с логированием
# ============================================================================

# Теперь все операции будут логироваться согласно установленному уровню
client = RuTrackerClient("your_login", "your_password")

# При уровне INFO вы увидите:
# - Успешную инициализацию клиента
# - Успешную аутентификацию
# - Результаты поиска (количество найденных результатов)
# - Успешную загрузку торрентов

# При уровне DEBUG вы увидите дополнительно:
# - Детали всех HTTP-запросов
# - Параметры поиска
# - Детали закрытия сессий

# Поиск с логированием
results = client.search("test", page=1)
print(f"Найдено результатов: {len(results)}")

# Логи будут выводиться в консоль и (если включено) записываться в файл
